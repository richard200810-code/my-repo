export const allColors: HairColor[] = shadeCodes.map((code) => ({
  code,
  series: 'additional',
  seriesLabel: 'Referencia de color',
  hasImage: false,
}));

export const colorsBySeries = { additional: allColors };
export const colorCounts = { additional: allColors.length, total: allColors.length };

export function searchColors(query: string): HairColor[] {
  const q = query.toLowerCase().trim();
  return q ? allColors.filter((color) => color.code.toLowerCase().includes(q)) : allColors;
}

export function getColorByCode(code: string): HairColor | undefined {
  return allColors.find((color) => color.code.toLowerCase() === code.toLowerCase());
}
